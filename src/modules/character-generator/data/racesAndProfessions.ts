const RACE_MAP = new Map<RaceId, RaceDefinition>(
  RACES_DATA.map((race) => [race.id, race])
);

const PROFESSION_MAP = new Map<CharacterProfessionId, ProfessionDefinition>(
  PROFESSIONS_DATA.map((prof) => [prof.id, prof])
);

export function getRaceDefinition(id: RaceId): RaceDefinition {
  const race = RACE_MAP.get(id);
  if (!race) throw new Error(`Unknown race id: ${id}`);
  return race;
}

export function getProfessionDefinition(
  id: CharacterProfessionId
): ProfessionDefinition {
  const prof = PROFESSION_MAP.get(id);
  if (!prof) throw new Error(`Unknown profession id: ${id}`);
  return prof;
}
